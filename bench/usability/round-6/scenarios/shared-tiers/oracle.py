#!/usr/bin/env python3
"""Grade an agent's final /work for the shared-tiers scenario.

python3 oracle.py DIR   -> prints PASS/FAIL and exits 0/1.

Runs DIR's invoicing program and the reference (pristine work/ + fix.patch) on the
original data and on hidden datasets generated by gen/make_data.py, and compares every
invoice's amounts (line codes, quantities and amounts, subtotal, tax, total).
Descriptions and notes are not compared.
"""
import json, shutil, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HIDDEN = [  # (name, generator args) - the generator is deterministic
    ("early-growth-upgrade", ["--seed", "11", "--customers", "900", "--heavy-growth", "300"]),
    ("starter-upgrade", ["--seed", "23", "--customers", "1000", "--heavy-starter", "200", "--heavy-growth", "700"]),
    ("several-upgrades", ["--seed", "5", "--customers", "800", "--heavy-growth", "100", "600", "--heavy-starter", "400",
                          "--contracts", "9"]),
]


def run(prog, data, out):
    r = subprocess.run([sys.executable, "run_invoices.py", str(data), "--period", "2026-09", "--out", str(out)],
                       cwd=prog, capture_output=True, text=True, timeout=120,
                       env={"PATH": "/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1"})
    if r.returncode != 0:
        raise RuntimeError(f"exit {r.returncode}: {r.stderr[-500:]}")
    return {i["number"]: i for i in map(json.loads, (Path(out) / "invoices.jsonl").read_text().splitlines())}


def essence(inv):
    return (inv["customer"], inv["currency"],
            tuple((l["code"], l["quantity"], round(l["amount"], 2)) for l in inv["lines"]),
            round(inv["subtotal"], 2), round(inv["tax"], 2), round(inv["total"], 2))


def main():
    agent_dir = Path(sys.argv[1]).resolve()
    with tempfile.TemporaryDirectory(prefix="oracle-shared-tiers-") as tmp:
        tmp = Path(tmp)
        agent = tmp / "agent"
        shutil.copytree(agent_dir, agent, ignore=shutil.ignore_patterns("__pycache__", "*.pmdb", "out"))
        ref = tmp / "ref"
        shutil.copytree(HERE / "work", ref, ignore=shutil.ignore_patterns("__pycache__"))
        p = subprocess.run(["patch", "-s", "-p1", "-d", str(ref)], stdin=open(HERE / "fix.patch"),
                           capture_output=True, text=True)
        if p.returncode != 0:
            print("ERROR reference patch failed", p.stdout, p.stderr); return 2
        datasets = [("original", HERE / "work" / "data")]
        for name, args in HIDDEN:
            d = tmp / "data" / name
            subprocess.run([sys.executable, str(HERE / "gen" / "make_data.py"), str(d), *args], check=True)
            datasets.append((name, d))
        for name, data in datasets:
            expected = run(ref, data, tmp / "out-ref" / name)
            try:
                got = run(agent, data, tmp / "out-agent" / name)
            except Exception as e:
                print(f"FAIL {name}: program failed: {e}"); return 1
            if set(got) != set(expected):
                print(f"FAIL {name}: invoice numbers differ"); return 1
            bad = [n for n in sorted(expected) if essence(got[n]) != essence(expected[n])]
            if bad:
                print(f"FAIL {name}: {len(bad)} of {len(expected)} invoices differ, first {bad[0]}"); return 1
        print(f"PASS all {len(datasets)} datasets match the reference")
        return 0


if __name__ == "__main__":
    sys.exit(main())
